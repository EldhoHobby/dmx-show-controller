// Builds the full "Neon Mile" demo: renders the track, analyses it, patches a club-sized rig
// and runs the show generator over the result.
//
//   node tools/make-demo-show.js
//
// Writes three things:
//   samples/neon-mile-128bpm.wav        the song itself (git-ignored, regenerate any time)
//   media/<sha256>[.json]               the engine's audio cache, so opening the show in the
//                                       app loads the song automatically instead of asking
//   shows/Neon Mile (128 BPM).dmxshow.json
//
// Everything it produces is ordinary show data: open it in Edit mode and change any of it.

import { createHash } from 'node:crypto';
import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

import { analyzeAudio } from '../shared/analysis/analyze.js';
import { generateShow } from '../shared/autogen.js';
import { createShow, exportShow, normalizeShow } from '../shared/show.js';
import { validateShow } from '../shared/validate.js';
import { buildFixtures, describeRig } from './rig.js';
import { SONG_FILE, SONG_NAME, encodeWavStereo, projectRoot, synthesizeSong } from './demo-song.js';

function main() {
  const root = projectRoot();

  process.stdout.write('Rendering the song… ');
  const song = synthesizeSong();
  const wav = encodeWavStereo(song.channels, song.sampleRate);
  const hash = createHash('sha256').update(wav).digest('hex');
  console.log(`${(song.durationMs / 1000).toFixed(1)} s, ${song.bpm} BPM, ${(wav.length / 1048576).toFixed(1)} MB`);

  mkdirSync(join(root, 'samples'), { recursive: true });
  writeFileSync(join(root, 'samples', SONG_FILE), wav);

  // Seed the engine's media cache so the show opens with its song already loaded.
  mkdirSync(join(root, 'media'), { recursive: true });
  writeFileSync(join(root, 'media', hash), wav);
  writeFileSync(join(root, 'media', `${hash}.json`), JSON.stringify({ type: 'audio/wav', name: `${SONG_NAME}.wav` }));

  process.stdout.write('Analysing… ');
  const result = analyzeAudio({ channels: song.channels, sampleRate: song.sampleRate });
  const { beats, downbeat, beatsPerBar, ...analysis } = result;
  console.log(
    `${result.bpm} BPM (confidence ${result.confidence.toFixed(2)}), ` +
      `${result.sections.length} sections, ${result.drops.length} drops`,
  );
  for (const s of result.sections) {
    console.log(`    ${fmt(s.start)} – ${fmt(s.end)}  ${s.label.padEnd(10)} energy ${s.energy.toFixed(2)}`);
  }

  const show = createShow(SONG_NAME);
  show.meta.notes =
    `Generated by tools/make-demo-show.js. ${describeRig()} ` +
    'Re-run the tool to rebuild the song and the timeline from scratch.';
  show.audio = { name: `${SONG_NAME}.wav`, hash, durationMs: Math.round(song.durationMs), sampleRate: song.sampleRate };
  show.fixtures = buildFixtures();
  show.tempo = { bpm: result.bpm, beats, downbeat, beatsPerBar, offset: beats[0] ?? 0 };
  show.analysis = analysis;
  show.timeline.durationMs = Math.round(result.durationMs);

  process.stdout.write('Generating the show… ');
  show.timeline = generateShow(show, { style: 'balanced' });
  console.log(`${show.timeline.clips.length} clips on ${show.timeline.tracks.length} tracks`);

  // Round-trip through the normalizer so the file is exactly what the app would have saved.
  const normalized = normalizeShow(show);
  const validation = validateShow(normalized);
  const out = exportShow(normalized, validation);

  for (const i of validation.issues) console.log(`  ${i.level === 'error' ? 'ERROR  ' : 'warning'} ${i.message}`);

  mkdirSync(join(root, 'shows'), { recursive: true });
  const file = join(root, 'shows', `${SONG_NAME}.dmxshow.json`);
  writeFileSync(file, `${JSON.stringify(out, null, 2)}\n`);
  console.log(
    `\nWrote ${file}\n` +
      `  ${out.fixtures.length} fixtures, ${out.timeline.clips.length} clips, ` +
      `${validation.errors} errors, ${validation.warnings} warnings`,
  );
}

const fmt = (ms) => `${Math.floor(ms / 60000)}:${String(Math.floor((ms % 60000) / 1000)).padStart(2, '0')}`;

main();
